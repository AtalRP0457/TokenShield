import type { Agent, AgentEvent, Incident } from '../types/api';
import { displayAgentName, perilFor } from './labels';
import { plainSentence } from './plain';
import { formatDateTimeMs, formatUsd, parseUtc } from './format';

/** A shareable Markdown report for one incident (paste into Slack, GitHub, Notion, email…). */
export function incidentReportMarkdown(i: Incident, agent: Agent | null | undefined, events: AgentEvent[]): string {
  const p = perilFor(i.incident_type);
  const g = i.gemini_analysis;
  const lines = [
    `# TokenShield incident report: ${i.id}`,
    '',
    `**${p.peril}: ${p.label}** · severity **${i.severity}** · status **${i.status}**`,
    '',
    `- Hero (agent): ${displayAgentName(i.agent_name)}${agent ? ` (${agent.status})` : ''}`,
    `- Detected: ${formatDateTimeMs(parseUtc(i.created_at))}`,
    `- Estimated waste: ${formatUsd(i.estimated_waste)} (estimate, not provider billing)`,
    ...(i.task_id ? [`- Task: ${i.task_id}`] : []),
    '',
    '## What happened, in plain words',
    '',
    g?.plain_explanation || plainSentence(i.incident_type),
    '',
    '## Detection',
    '',
    i.description,
  ];
  const ev = Object.entries(i.evidence ?? {});
  if (ev.length) lines.push('', ...ev.map(([k, v]) => `- ${k.replace(/_/g, ' ')}: ${typeof v === 'object' ? JSON.stringify(v) : String(v)}`));
  if (g) {
    lines.push('', "## The Oracle's reading (Gemini)", '', g.summary, '', `**Probable root cause:** ${g.probable_root_cause}`, '', `Confidence: ${Math.round(g.confidence * 100)}%`);
    if (g.recommended_actions.length) lines.push('', '## Recommended actions', '', ...g.recommended_actions.map((a) => `1. ${a}`));
  }
  const related = events.filter((e) => (i.task_id ? e.task_id === i.task_id : true)).slice(0, 15);
  if (related.length) {
    lines.push('', '## Recent events', '', '| Time | Step | Result | Est. cost |', '|---|---|---|---|');
    for (const e of related) {
      lines.push(`| ${formatDateTimeMs(parseUtc(e.timestamp))} | ${e.tool_name ?? e.event_type} | ${e.success === false ? `failed${e.error_message ? `: ${e.error_message}` : ''}` : 'ok'} | ${formatUsd(e.estimated_cost ?? 0)} |`);
    }
  }
  lines.push('', '---', '_Generated by TokenShield (Aegis). All costs are estimates._', '');
  return lines.join('\n');
}

export function downloadText(filename: string, text: string, type = 'text/markdown') {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}
